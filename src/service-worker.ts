/** The shell precache manifest inlined into the generated service worker. */
export interface ServiceWorkerManifest {
  readonly version: string;
  readonly pages: readonly string[];
  readonly assets: readonly string[];
}

export const SHELL_CACHE_PREFIX = "maski-shell-";

export function precacheUrls(manifest: ServiceWorkerManifest): string[] {
  return [...manifest.pages, ...manifest.assets];
}

function isStringArray(value: unknown): value is readonly string[] {
  if (!Array.isArray(value)) return false;
  for (const item of value) {
    if (typeof item !== "string") return false;
  }
  return true;
}

const pagesPattern = /const PAGES = (\[[^;]*\]);/u;
const assetsPattern = /const ASSETS = (\[[^;]*\]);/u;
const versionPattern = /const VERSION = "([^"]+)";/u;

export function parseServiceWorkerManifest(source: string): ServiceWorkerManifest | null {
  const rawPages = pagesPattern.exec(source)?.[1];
  const rawAssets = assetsPattern.exec(source)?.[1];
  const version = versionPattern.exec(source)?.[1];
  if (rawPages === undefined || rawAssets === undefined || version === undefined) return null;

  let pages: unknown;
  let assets: unknown;
  try {
    pages = JSON.parse(rawPages);
    assets = JSON.parse(rawAssets);
  } catch {
    return null;
  }
  if (!isStringArray(pages) || !isStringArray(assets)) return null;
  return { version, pages, assets };
}

/*
 * The service worker is generated source rather than a bundled entry: the shell
 * manifest has to be inlined so install can precache the exact shell without a
 * second fetch. Cache writes are reachable only through the shell page and shell
 * asset guards below; no other response can enter the cache.
 */
export function serviceWorkerSource(manifest: ServiceWorkerManifest): string {
  return `/* Generated by scripts/build.ts. Do not edit. */
const VERSION = ${JSON.stringify(manifest.version)};
const CACHE_PREFIX = ${JSON.stringify(SHELL_CACHE_PREFIX)};
const CACHE = CACHE_PREFIX + VERSION;
const PAGES = ${JSON.stringify(manifest.pages)};
const ASSETS = ${JSON.stringify(manifest.assets)};
const SHELL_PAGES = new Set(PAGES);
const SHELL_ASSETS = new Set(ASSETS);

self.addEventListener("install", (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE);
    const requests = PAGES.concat(ASSETS).map((path) => new Request(path, { credentials: "omit", cache: "no-store" }));
    await cache.addAll(requests);
    await self.skipWaiting();
  })());
});

self.addEventListener("activate", (event) => {
  event.waitUntil((async () => {
    const keys = await caches.keys();
    await Promise.all(keys.filter((key) => key.startsWith(CACHE_PREFIX) && key !== CACHE).map((key) => caches.delete(key)));
    await self.clients.claim();
  })());
});

function isShellResponse(response) {
  if (!response.ok || response.redirected || response.type !== "basic") return false;
  const type = (response.headers.get("content-type") || "").toLowerCase();
  return type.startsWith("text/html");
}

async function cachedPage(path) {
  const cache = await caches.open(CACHE);
  const cached = await cache.match(path);
  if (cached !== undefined) return cached;
  try {
    return await fetch(path, { credentials: "omit", cache: "no-store" });
  } catch {
    return Response.error();
  }
}

async function revalidatePage(path) {
  try {
    const response = await fetch(path, { credentials: "omit", cache: "no-store" });
    if (!isShellResponse(response)) return;
    const cache = await caches.open(CACHE);
    await cache.put(path, response);
  } catch {
    // Offline is normal; the cached shell stays live.
  }
}

async function cachedAsset(path) {
  const cache = await caches.open(CACHE);
  const cached = await cache.match(path);
  if (cached !== undefined) return cached;
  return fetch(path);
}

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;

  if (request.mode === "navigate" && SHELL_PAGES.has(url.pathname)) {
    event.respondWith(cachedPage(url.pathname));
    event.waitUntil(revalidatePage(url.pathname));
    return;
  }

  if (SHELL_ASSETS.has(url.pathname)) event.respondWith(cachedAsset(url.pathname));
});
`;
}
