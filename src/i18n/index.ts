export const catalogs: Record<Locale, Catalog> = {
  en,
  "zh-CN": zhCN,
};

let currentLocale: Locale = config.app.defaultLocale;

export function setLocale(locale: Locale): void {
  currentLocale = locale;
}

export function getLocale(): Locale {
  return currentLocale;
}

export function isLocale(value: string): value is Locale {
  return config.app.locales.some((locale) => locale === value);
}

export function localePath(locale: Locale): string {
  return locale === config.app.defaultLocale ? "/" : `/${locale}/`;
}

export function localeFromPath(path: string): Locale | null {
  const segment = path.split("/").find((part) => part.length > 0);
  if (!segment) return null;
  return isLocale(segment) ? segment : null;
}

export function stripLocale(path: string): string {
  const segments = path.split("/");
  const first = segments[1];
  if (first && isLocale(first)) {
    const rest = segments.slice(2).join("/");
    return rest ? `/${rest}` : "/";
  }
  return path || "/";
}

export function withLocale(locale: Locale, path: string): string {
  const clean = path.startsWith("/") ? path : `/${path}`;
  if (locale === config.app.defaultLocale) return clean;
  return clean === "/" ? `/${locale}/` : `/${locale}${clean}`;
}

export function t(key: MessageKey, params: Record<string, string | number> = {}): string {
  return translate(currentLocale, key, params);
}

export function translate(
  locale: Locale,
  key: MessageKey,
  params: Record<string, string | number> = {},
): string {
  const value = catalogs[locale][key] ?? catalogs[config.app.fallbackLocale][key] ?? key;
  return interpolate(value, { app: config.app.name, ...params });
}

function interpolate(value: string, params: Record<string, string | number>): string {
  return value.replace(/\{(\w+)\}/g, (match, name: string) => {
    const param = params[name];
    return param === undefined ? match : String(param);
  });
}

export function formatTime(locale: Locale, ts: number): string {
  return new Intl.DateTimeFormat(locale, { hour: "2-digit", minute: "2-digit" }).format(ts);
}

export function formatDate(locale: Locale, ts: number): string {
  return new Intl.DateTimeFormat(locale, {
    year: "numeric",
    month: "short",
    day: "numeric",
  }).format(ts);
}

export function formatNumber(locale: Locale, value: number): string {
  return new Intl.NumberFormat(locale).format(value);
}

export function formatRelative(locale: Locale, ts: number, now = Date.now()): string {
  const diff = ts - now;
  const abs = Math.abs(diff);
  const rtf = new Intl.RelativeTimeFormat(locale, { numeric: "auto" });
  if (abs < 60_000) return rtf.format(Math.round(diff / 1000), "second");
  if (abs < 3_600_000) return rtf.format(Math.round(diff / 60_000), "minute");
  if (abs < 86_400_000) return rtf.format(Math.round(diff / 3_600_000), "hour");
  return rtf.format(Math.round(diff / 86_400_000), "day");
}
